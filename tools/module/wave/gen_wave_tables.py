"""WAVE's starter wavetables (docs/candidates/wave.md 3 and 7): four tables of eight frames, each frame one cycle of 256 int16 samples (the top level: at most 128
harmonics, so every frame is band-limited as written; the engine halves a frame per note down to what its pitch allows). Our own, additive: no table of any
other instrument is read. Writes tools/module/wave/wave_tables.h (committed, so a build needs no numpy).

  BASIC     sine -> triangle -> saw -> square, the harmonics' weights moving between the classic shapes
  PULSE     pulse widths 50 % down to 6 %
  VOWEL     the vowels a, e, i, o, u and between them: a saw through two formant peaks (the cascade's peaks moved per frame)
  BRIGHT    from the fundamental alone up to 64 partials with a rising tilt and inharmonic-sounding gaps (odd harmonics boosted, even ones notched)

  python3 tools/module/wave/gen_wave_tables.py [out.h]
"""
import sys
from pathlib import Path
import numpy as np

N, NF, H = 256, 8, 128
t = np.arange(N) / N


def frame(amps, phases=None):
    """one cycle from harmonic amplitudes amps[1..H] (sines), normalised to a peak of 0.95"""
    x = np.zeros(N)
    for h in range(1, min(H, len(amps) - 1) + 1):
        a = amps[h]
        if a:
            x += a * np.sin(2 * np.pi * h * t + (phases[h] if phases is not None else 0.0))
    m = np.abs(x).max()
    return x / m * 0.95 if m > 0 else x


def lerp(a, b, f):
    return (1 - f) * a + f * b


def basic():
    h = np.arange(H + 1, dtype=float)
    sine = np.zeros(H + 1); sine[1] = 1
    tri = np.zeros(H + 1); tri[1::2] = [((-1) ** k) / (2 * k + 1) ** 2 for k in range(len(tri[1::2]))]
    saw = np.zeros(H + 1); saw[1:] = 1 / h[1:]
    sq = np.zeros(H + 1); sq[1::2] = 1 / h[1::2]
    keys = [sine, tri, saw, sq]
    out = []
    for f in range(NF):                                  # 8 frames across the 3 spans
        p = f / (NF - 1) * 3
        k = min(int(p), 2)
        out.append(frame(lerp(keys[k], keys[k + 1], p - k)))
    return out


def pulse():
    out = []
    h = np.arange(H + 1, dtype=float)
    for f in range(NF):
        w = 0.5 - f / (NF - 1) * 0.44                    # 50 % .. 6 %
        a = np.zeros(H + 1)
        a[1:] = np.sin(np.pi * h[1:] * w) / h[1:]
        ph = np.zeros(H + 1); ph[1:] = -np.pi * h[1:] * w + np.pi / 2
        out.append(frame(a, ph))
    return out


VOWELS = [(800, 1150), (400, 2000), (270, 2300), (450, 800), (325, 700)]   # a e i o u: F1, F2 (Hz), for a 110 Hz voice


def vowel():
    out = []
    h = np.arange(H + 1, dtype=float)
    for f in range(NF):
        p = f / (NF - 1) * (len(VOWELS) - 1)
        k = min(int(p), len(VOWELS) - 2)
        f1 = lerp(VOWELS[k][0], VOWELS[k + 1][0], p - k)
        f2 = lerp(VOWELS[k][1], VOWELS[k + 1][1], p - k)
        hz = h * 110.0
        env = 1 / (1 + ((hz - f1) / 90) ** 2) + 0.7 / (1 + ((hz - f2) / 140) ** 2) + 0.02
        a = np.zeros(H + 1); a[1:] = env[1:] / h[1:] ** 0.5
        out.append(frame(a))
    return out


def bright():
    out = []
    h = np.arange(H + 1, dtype=float)
    for f in range(NF):
        n = int(round(2 ** (f * 6 / (NF - 1))))          # 1 .. 64 partials
        a = np.zeros(H + 1)
        tilt = 0.5 + f / (NF - 1)                         # the tilt rises with the frame
        for k in range(1, n + 1):
            a[k] = (1 / k ** (1.5 - tilt)) * (1.6 if k % 2 else (0.35 if k % 4 == 0 else 0.8))
        out.append(frame(a))
    return out


TABLES = [("BASIC", basic), ("PULSE", pulse), ("VOWEL", vowel), ("BRIGHT", bright)]


def main(out):
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only", " * Copyright 2026 Jeremiah Conner.",
             " * Generated by tools/module/wave/gen_wave_tables.py: WAVE's starter wavetables (our own, additive). Do not edit. */",
             "#pragma once", "#include <stdint.h>", f"#define WV_NTAB {len(TABLES)}u", f"#define WV_NFRAME {NF}u", f"#define WV_FLEN {N}u",
             "static const char *const WV_TAB_NAMES[WV_NTAB] = {" + ", ".join(f'"{n}"' for n, _ in TABLES) + "};",
             "static const int16_t WV_TABLES[WV_NTAB][WV_NFRAME * WV_FLEN] = {"]
    for name, fn in TABLES:
        fr = fn()
        v = np.concatenate([np.round(x * 32767).astype(int) for x in fr])
        lines.append(f"    {{   /* {name} */")
        for i in range(0, len(v), 16):
            lines.append("        " + ", ".join(str(int(s)) for s in v[i:i + 16]) + ",")
        lines.append("    },")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).parent / "wave_tables.h"))
