"""Orange Cat, the engine candidates gate (docs/orangecat/ENGINE_CANDIDATES.md, "CZ-1"): FM6_SIN as constant data, for the CZ-1 module.

The CZ-1's oscillator (firmware/src/cz_native.c cz_native_wave) reads FM6_SIN[1025] (float) every sample. The firmware fills that table in RAM at boot
(melodee_tables.h dsp_tables_init: a rotation by FM6_SIN_C, FM6_SIN_S in 64-bit integers, then x / 2^24). A module has no RAM of its own, so it
carries the table as constants (its hot set, copied into the arena when it registers): this is dsp_tables_init's arithmetic, each value written as
the exact hex float (x < 2^24 is exact in a float). tests/module_host_cz_test.c checks it against the firmware's table, value for value.
    tools/module/cz/gen_cz_fm6_sin.py [build/gen/melodee_tables.h]       (rewrites tools/module/cz/cz_fm6_sin.h)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "build/gen/melodee_tables.h"
t = src.read_text()
C = int(re.search(r"#define FM6_SIN_C (\d+)", t).group(1))
S = int(re.search(r"#define FM6_SIN_S (\d+)", t).group(1))
sin = [0.0] * 1025
u, v = 1 << 30, 0
for i in range(512):
    x = (v + 32) >> 6
    sin[i] = x / 16777216.0
    sin[i + 512] = -x / 16777216.0
    x = (u * C - v * S + (1 << 29)) >> 30
    v = (u * S + v * C + (1 << 29)) >> 30
    u = x
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         f"/* GENERATED by tools/module/cz/gen_cz_fm6_sin.py (FM6_SIN_C {C}, FM6_SIN_S {S}) - do not edit. The firmware's FM6_SIN[1025] as constants: the",
         " * CZ-1 module's hot set (Orange Cat). */",
         "static const float CZ_FM6_SIN[1025] = {"]
for i in range(0, 1025, 8):
    lines.append("    " + ", ".join((v.hex() + "f") if v else "0.0f" for v in sin[i:i + 8]) + ",")
lines.append("};")
(HERE / "cz_fm6_sin.h").write_text("\n".join(lines) + "\n")
print(f"cz_fm6_sin.h: 1025 floats, 4100 B (C {C}, S {S})")
