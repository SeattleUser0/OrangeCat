"""Orange Cat, the engine candidates gate (docs/orangecat/ENGINE_CANDIDATES.md, "op1r"): brassophone's phase warp table, every fourth column.

op1r's brassophone (plugins/brassophone/brass.c, nick (nvmsocool)) reads warp_table[64][257] (int16, 32,896 B, warp_table.h from its
gen_warp_table.py) four times a sample, bilinear in (the oscillator's phase row, the timbre column). Per sample, from flash, that breaks the cache
rule (docs/orangecat/ADDING_AN_ENGINE.md, section 4), and as a hot set it would take half the audio arena. The module reads this instead: the same
rows at columns 0, 4, .., 256 (65) and the last one again (66: the read of column c + 1 at c = 256 stays inside), 8,448 B, its hot set; a column
between is the linear interpolation of its two neighbours (tools/module/brassophone_mod.c brass_warp). Against op1r's own columns that is at most
6 LSB of the Q15 warped phase (this script prints it); tests/op1r_parity measures what it does to the sound.
    tools/module/op1r/gen_brass_warp4.py           (rewrites brass_warp4.h from plugins/brassophone/warp_table.h)
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "plugins/brassophone/warp_table.h").read_text()
body = t[t.index("{", t.index("warp_table[64][257]")):]
nums = [int(x) for x in re.findall(r"-?\d+", re.sub(r"//[^\n]*", "", body))][:64 * 257]
w = [nums[r * 257:(r + 1) * 257] for r in range(64)]
w4 = [[row[c] for c in range(0, 257, 4)] + [row[256]] for row in w]
err = 0
for row, r4 in zip(w, w4):
    for c in range(257):
        j, f = c >> 2, c & 3
        err = max(err, abs(r4[j] + (((r4[j + 1] - r4[j]) * f + 2) >> 2) - row[c]))
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/module/op1r/gen_brass_warp4.py from plugins/brassophone/warp_table.h (op1r bf808cfa, nick (nvmsocool)) - do not edit.",
         f" * brassophone's warp_table at every fourth column (0, 4, .., 256) and column 256 again: 64 x 66 int16, {64 * 66 * 2} B (Orange Cat: its hot set;",
         f" * a column between interpolated, at most {err} LSB from op1r's). */",
         "static const int16_t BRASS_WARP4[64][66] = {"]
for r4 in w4:
    lines.append("    { " + ", ".join(str(v) for v in r4) + " },")
lines.append("};")
(HERE / "brass_warp4.h").write_text("\n".join(lines) + "\n")
print(f"brass_warp4.h: 64 x 66, {64 * 66 * 2} B; at most {err} LSB from op1r's columns")
