"""Orange Cat, the engine candidates gate (docs/orangecat/ENGINE_CANDIDATES.md, "op1r"): arc's tuning table, decoded once here instead of at run time.

op1r's arc (plugins/arc/arc.c, ultralazr) stores its G table compressed (ARC_GPZ, ARC_GPROW in arc_tables.h) and decodes it into a file-scope RAM
array, arc_gp[ARC_KN][ARC_PN], from its screen's init or on first use in render (gp_decode). A module has no RAM of its own, and gp_decode and
gp_of have no voice object through which the part's state could be reached; the table is read once a block (lamp_setup). So the module carries it
decoded, in flash: this is gp_decode's arithmetic (row k from row k - 1: int8 residuals, -128 an escape to an int16, the tail repeating the last
node), writing tools/module/op1r/arc_gp.h, which the vendored arc.c includes in place of its RAM array (the lines marked Orange Cat).
tests/op1r_parity proves it: arc through the module with op1r's own sine must equal op1r's render (which decodes at run time) in every sample.
    tools/module/op1r/gen_arc_gp.py            (rewrites arc_gp.h from plugins/arc/arc_tables.h)
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "plugins/arc/arc_tables.h").read_text()
KN = int(re.search(r"#define ARC_KN (\d+)", t).group(1))
PN = int(re.search(r"#define ARC_PN (\d+)", t).group(1))
row = [int(x) for x in re.search(r"ARC_GPROW\[ARC_KN\] = \{([^}]*)\}", t).group(1).split(",")]
gpz = [int(x) for x in re.search(r"ARC_GPZ\[\d+\] = \{([^}]*)\}", t, re.S).group(1).replace("\n", " ").split(",") if x.strip()]
gp = []
for k in range(KN):
    z = row[k]
    up = gp[k - 1] if k > 0 else [0] * PN
    g = ul = 0
    n = gpz[z]
    z += 1
    out = []
    for p in range(PN):
        if p < n:
            d, u = gpz[z], up[p] if k > 0 else 0
            z += 1
            if d == -128:
                d = (gpz[z] & 0xFF) + gpz[z + 1] * 256
                z += 2
            g += d + u - ul
            ul = u
        out.append(g & 0xFFFF)
    gp.append(out)
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/module/op1r/gen_arc_gp.py from plugins/arc/arc_tables.h (op1r bf808cfa, ultralazr) - do not edit. arc's G table as its",
         " * gp_decode leaves it in RAM, decoded here once (Orange Cat: a module has no RAM of its own; read once a block). */",
         f"static const uint16_t arc_gp[ARC_KN][ARC_PN] = {{"]
for r in gp:
    lines.append("    { " + ", ".join(str(v) for v in r) + " },")
lines.append("};")
(HERE / "arc_gp.h").write_text("\n".join(lines) + "\n")
print(f"arc_gp.h: {KN} x {PN}, {2 * KN * PN} B")
