"""Orange Cat, the engine candidates gate (docs/orangecat/ENGINE_CANDIDATES.md, "op1r"): op1r's sine as a quarter wave, for OP1G_EXACT_SINE.

op1r's harness fills its 8192-point sine table with lrint(32767 sin(2 pi k / 8192)); the glue's default OP1_SINE(k) is dsp.c's SINE[1025] interpolated,
at most 1 LSB off. A plugin whose sine drives a pitch (brassophone's vibrato) turns that LSB into phase drift; it can read this instead: k = 0..2048
(4,098 B, a hot set table), the other three quarters by symmetry (op1_glue.h op1g_sine), which equals op1r's table at all 8192 points (this script
checks it). Rounding: Python's round is half to even, as lrint in the default mode.
    tools/module/op1r/gen_op1_sine.py           (rewrites op1_sine_q.h)
"""
import math
from pathlib import Path

full = [round(32767.0 * math.sin(2 * math.pi * k / 8192.0)) for k in range(8192)]
q = full[:2049]


def by_symmetry(k):
    k &= 8191
    i = k & 2047
    v = q[i] if not (k >> 11) & 1 else q[2048 - i]
    return -v if k >> 12 else v


assert all(by_symmetry(k) == full[k] for k in range(8192)), "the quarter wave does not make op1r's table"
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/module/op1r/gen_op1_sine.py - do not edit. op1r's sine table (lrint(32767 sin(2 pi k / 8192))), its first quarter and the",
         " * peak: k = 0..2048, 4,098 B (Orange Cat: op1_glue.h OP1G_EXACT_SINE makes the other quarters by symmetry, op1r's table at all 8192 points). */",
         "static const int16_t OP1G_SINE_Q[2049] = {"]
for i in range(0, 2049, 16):
    lines.append("    " + ", ".join(str(v) for v in q[i:i + 16]) + ",")
lines.append("};")
(Path(__file__).resolve().parent / "op1_sine_q.h").write_text("\n".join(lines) + "\n")
print("op1_sine_q.h: 2049 points, 4098 B; equal to op1r's table at all 8192 by symmetry")
