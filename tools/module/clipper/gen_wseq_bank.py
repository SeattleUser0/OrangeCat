"""Orange Cat, the engine candidates gate (docs/orangecat/ENGINE_CANDIDATES.md, "Clipper"; ENGINE_LOADING_PLAN.md, "Shared backends"): WSEQ's waves in
the shared wavetable format (tools/module/clipper/wt_shared.h).

Clipper's WSEQ plays FMX's waves (Clipper's fmx_tables.h, from its tools/gen_fmx.py: 1024-point single cycles, SAW SQR PULSE with 8-harmonic copies for
the high notes; read per sample: 26,624 B). Here they are made into wt_shared.h's bank (each wave in three band-limited copies, 512 points to the 96th
harmonic, 128 to the 24th, 32 to the 6th, with VECTOR's soft roll-off at each copy's top: its tools/gen_vector.py `soft`): each FMX wave's spectrum is
taken from its 1024 points (an FFT), cut and rolled off as the copy allows, and written back at that length, at FMX's own scale (no level change).
SINE and NOISE stay arithmetic (WSEQ's sine_i and generator): the bank holds TRI SAW SQR HALF ABS QUART PULSE SIN8, 8 frames, 10,752 B.
    gen_wseq_bank.py <Clipper's fmx_tables.h>       (rewrites tools/module/clipper/wseq_bank.h; needs numpy)
"""
import re
import sys
from pathlib import Path

import numpy as np

WAVES = ["TRI", "SAW", "SQR", "HALF", "ABS", "QUART", "PULSE", "SIN8"]   # FMX's FXW_TRI .. FXW_SIN8 (1 .. 8)
LEVELS = [(512, 96), (128, 24), (32, 6)]
t = Path(sys.argv[1]).read_text()
body = t[t.index("FMX_WAVE[FMX_WN][FMX_TN] = {"):]
rows = re.findall(r"\{\s*/\*\s*(\w+)\s*\*/(.*?)\}", body, re.S)
tab = {n: np.array([int(x) for x in v.replace("\n", " ").split(",") if x.strip()], dtype=float) for n, v in rows}
out, peak = [], 0
for w in WAVES:
    x = tab[w]
    assert len(x) == 1024, (w, len(x))
    X = np.fft.rfft(x)
    frame = []
    for n, nh in LEVELS:
        Y = np.zeros(n // 2 + 1, dtype=complex)
        for k in range(1, nh + 1):
            Y[k] = X[k] * (0.5 + 0.5 * np.cos(np.pi * k / (nh + 1))) * (n / 1024)
        Y[0] = X[0] * (n / 1024)
        y = np.fft.irfft(Y, n)
        frame += [max(-32767, min(32767, int(round(v)))) for v in y]   # (a band limit's ringing over a square's edge: 0.1 % past full scale, clipped)
    peak = max(peak, max(abs(v) for v in np.fft.irfft(X, 1024)))
    out.append((w, frame))
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/module/clipper/gen_wseq_bank.py from Clipper's fmx_tables.h (e690672, 3dSam) - do not edit. WSEQ's waves (FMX's TRI SAW",
         " * SQR HALF ABS QUART PULSE SIN8) in wt_shared.h's bank format: three band-limited copies each (512 / 128 / 32 points to harmonics 96 / 24 / 6). */",
         "#define WSEQ_BANK_N 8u",
         "static const int16_t WSEQ_BANK[WSEQ_BANK_N][WTS_PTS] = {"]
for w, f in out:
    lines.append(f"    {{   /* {w} */")
    for i in range(0, len(f), 16):
        lines.append("        " + ", ".join(str(v) for v in f[i:i + 16]) + ",")
    lines.append("    },")
lines.append("};")
(Path(__file__).resolve().parent / "wseq_bank.h").write_text("\n".join(lines) + "\n")
print(f"wseq_bank.h: {len(out)} frames, {len(out) * 672 * 2} B, peak {peak}")
