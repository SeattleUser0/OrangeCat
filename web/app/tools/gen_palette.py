"""Orange Cat web app: web/app/lib/palette.js from the device's own palettes (tools/gen_ui_palettes.py).

  python3 web/app/tools/gen_palette.py            write web/app/lib/palette.js
  python3 web/app/tools/gen_palette.py --check    exit 1 when it differs (web/app/test/run.mjs runs this)

The page takes the unit's colors, not colors of its own: each palette's background, surface, text and four track colors, and
each track's four knob shades exactly as the firmware's screen gets them (gen_ui_palettes.shades: the track's color turned
round the OKLCH hue circle, knob 1 the track's own). So the knobs on the page are the colors of the knobs on the unit, and a
change to the device's palettes (Session C's new interface) reaches the page by running this again.

Revisions:
  0.14.2: first version (Session D).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import gen_ui_palettes as P  # noqa: E402

OUT = HERE.parent / "lib" / "palette.js"


def hexc(c):
    return "#%02X%02X%02X" % tuple(c)


def text():
    pals = []
    for p in P.PALETTES:
        name, bg, surf, txt, accent, trk = p
        pals.append({"name": name, "bg": hexc(bg), "surface": hexc(surf), "text": hexc(txt), "accent": hexc(accent),
                     "tracks": [hexc(c) for c in trk], "knobs": [[hexc(c) for c in row] for row in P.shades(p)]})
    return ("// SPDX-License-Identifier: GPL-3.0-only\n"
            "// GENERATED by web/app/tools/gen_palette.py from tools/gen_ui_palettes.py (the unit's palettes and knob shades). Do not edit.\n"
            "export const PALETTES = " + json.dumps(pals, indent=1) + ";\n")


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != t:
            sys.exit("web/app/lib/palette.js differs from tools/gen_ui_palettes.py: run python3 web/app/tools/gen_palette.py")
        print("palette.js matches the device's palettes")
    else:
        OUT.write_text(t)
        print(f"wrote {OUT}")
