// Orange Cat web app: web/app/lib/fw_tables.js from the firmware's own C (tests/web_tables.c), as the Nightly has it.
//
//   build/host/web_tables > build/host/web/fw_tables.json     (tests/run_tests.sh does it, with the Nightly's switches)
//   node web/app/tools/gen_fw_tables.mjs build/host/web         write web/app/lib/fw_tables.js from that folder
//   node web/app/tools/gen_fw_tables.mjs build/host/web --check exit 1 when it differs (the firmware changed and the app was not regenerated)
//
// What it holds: the parameter tables, the page table in the firmware's order, HOME's four knobs of the built-in engines, the system menu,
// the shortcut layers and DUB's keys. web/app/lib/model.js and the controls guide (docs/orangecat/CONTROLS.md, web/app/tools/gen_controls.mjs)
// read these and nothing is copied by hand; web/app/test/test_tables.mjs fails when the firmware and this file differ, and when a page, a
// parameter, a menu item or a layer is not covered by the app or the guide.
//
// Revisions:
//   web-r3: first version (Session D).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, "..", "lib", "fw_tables.js");

/* what MOD_INFO answers that is oc_module.c's own text: the number of starts and sectors, every start's sector from 0xC8000, and each engine's sectors and
   allowed starts (oc_mod_geo). Read from the source, not copied: a changed geometry changes this file, and test_tables.mjs says so. */
export function modFromSource() {
  const src = readFileSync(join(HERE, "..", "..", "..", "firmware", "src", "oc_module.c"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const num = (name) => +new RegExp(`#define ${name}\\s+(\\d+)u`).exec(src)[1];
  const sect = /oc_mod_sect\[OC_MOD_STARTS\]\s*=\s*\{([^}]*)\}/.exec(src)[1].split("#if")[0].split(",").map((x) => x.trim()).filter(Boolean).map(Number);   /* (round 23) the area's starts: the tail region's three (OC_MOD_TAIL, FLASH_MAP_R3.md 10) follow under #if and are not in this table (the app's mock is a unit with 18 starts) */
  const geoText = /oc_mod_geo\[\]\s*=\s*\{([\s\S]*?)\n\s*\};/.exec(src)[1].replace(/#if OC_MOD_TAIL[\s\S]*?#else([\s\S]*?)#endif/g, "$1").replace(/#if[\s\S]*?#endif/g, "");   /* (round 23) the geometry without the tail region (WHEEL's published 4 sectors): the mock is a unit with 18 starts */
  const geo = [...geoText.matchAll(/\{\s*ENGI_([A-Z0-9]+),\s*(\d+)u,\s*(0x[0-9A-Fa-f]+)u\s*\}/g)].map((m) => ({ engine: m[1], sectors: +m[2], starts: parseInt(m[3], 16) }));
  return { starts: num("OC_MOD_AREA_STARTS"), area: num("OC_MOD_AREA"), sect, geo };
}
export function tablesText(json) {
  json = { ...json, mod: { ...json.mod, ...modFromSource() } };
  return "// SPDX-License-Identifier: GPL-3.0-only\n" +
    "// GENERATED by web/app/tools/gen_fw_tables.mjs from tests/web_tables.c (the firmware's own tables, with the Nightly's build switches). Do not edit.\n" +
    "export const FW = " + JSON.stringify(json, null, 1) + ";\n";
}
export function check(dir) {
  const json = JSON.parse(readFileSync(join(dir, "fw_tables.json"), "utf8"));
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  return now === tablesText(json) ? [] : ["web/app/lib/fw_tables.js differs from tests/web_tables.c's JSON (the firmware's pages, parameters, knobs, menu or layers changed)"];
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = process.argv[2];
  if (!dir) { console.error("usage: gen_fw_tables.mjs DIR [--check]"); process.exit(2); }
  if (process.argv.includes("--check")) {
    const p = check(dir);
    if (p.length) { console.error(p.join("\n") + "\nrun: node web/app/tools/gen_fw_tables.mjs " + dir); process.exit(1); }
    console.log("fw_tables.js matches the firmware");
  } else {
    writeFileSync(OUT, tablesText(JSON.parse(readFileSync(join(dir, "fw_tables.json"), "utf8"))));
    console.log("wrote " + OUT);
  }
}
