// Orange Cat web app: web/app/lib/layout.js from the firmware's own C (tests/app_layout.c), and the fixtures it writes.
//
//   cc ... -o build/host/app_layout tests/app_layout.c                 (tests/run_tests.sh does it)
//   build/host/app_layout json > build/host/app/layout.json
//   build/host/app_layout fixtures build/host/app
//   node web/app/tools/gen_layout.mjs build/host/app          write web/app/lib/layout.js and tests/fixtures/app/*.bin from that folder
//   node web/app/tools/gen_layout.mjs build/host/app --check  exit 1 when either differs (the firmware changed and the app was not regenerated)
//
// The codec (web/app/lib/codec.js) reads every offset, size and count from LAYOUT, and the fixtures are records the firmware wrote,
// which the codec must read and write back byte for byte (web/app/test/test_codec.mjs). So a firmware change to the project record
// fails the web tests until this is run again, and then fails them again if the codec no longer round-trips the new records.
//
// Revisions:
//   0.14.2: first version (Session D).

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const OUT = join(HERE, "..", "lib", "layout.js");
const FIX = join(ROOT, "tests", "fixtures", "app");
const MOCK = join(HERE, "..", "lib", "mock_data.js");

/* the mocked unit's music (web/app/lib/mock.js, ?mock in the page): the firmware's own fixture records, base64, loaded only in mock mode */
export function mockText(dir) {
  const b64 = (f) => readFileSync(join(dir, f)).toString("base64");
  return "// SPDX-License-Identifier: GPL-3.0-only\n" +
    "// GENERATED by web/app/tools/gen_layout.mjs from the fixtures tests/app_layout.c writes (records the firmware made). Do not edit.\n" +
    `export const FBKK_FULL = "${b64("fbkk-full.bin")}";\n` +
    `export const FBKK_ONE_BANK = "${b64("fbkk-one-bank.bin")}";\n` +
    `export const FBKK_NEW = "${b64("fbkk-new.bin")}";\n` +
    `export const LISTS_SONG = "${b64("lists-song.bin")}";\n` +
    `export const LISTS_NEW = "${b64("lists-new.bin")}";\n`;
}

export function layoutText(json) {
  return "// SPDX-License-Identifier: GPL-3.0-only\n" +
    "// GENERATED by web/app/tools/gen_layout.mjs from tests/app_layout.c (the firmware's own macros, structs and tables). Do not edit.\n" +
    "export const LAYOUT = " + JSON.stringify(json, null, 1) + ";\n";
}

export function check(dir) {
  const problems = [];
  const json = JSON.parse(readFileSync(join(dir, "layout.json"), "utf8"));
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== layoutText(json)) problems.push("web/app/lib/layout.js differs from tests/app_layout.c's JSON");
  if (!existsSync(MOCK) || readFileSync(MOCK, "utf8") !== mockText(dir)) problems.push("web/app/lib/mock_data.js differs from the fixtures");
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".bin"))) {
    const fresh = readFileSync(join(dir, f)), kept = existsSync(join(FIX, f)) ? readFileSync(join(FIX, f)) : null;
    if (!kept || !kept.equals(fresh)) problems.push(`tests/fixtures/app/${f} differs from what the firmware writes now`);
  }
  return problems;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = process.argv[2];
  if (!dir) { console.error("usage: gen_layout.mjs DIR [--check]"); process.exit(2); }
  if (process.argv.includes("--check")) {
    const p = check(dir);
    if (p.length) { console.error(p.join("\n") + "\nrun: node web/app/tools/gen_layout.mjs " + dir); process.exit(1); }
    console.log("layout.js and the app fixtures match the firmware");
  } else {
    const json = JSON.parse(readFileSync(join(dir, "layout.json"), "utf8"));
    writeFileSync(OUT, layoutText(json));
    writeFileSync(MOCK, mockText(dir));
    mkdirSync(FIX, { recursive: true });
    for (const f of readdirSync(dir).filter((x) => x.endsWith(".bin"))) writeFileSync(join(FIX, f), readFileSync(join(dir, f)));
    console.log(`wrote ${OUT} and tests/fixtures/app/`);
  }
}
