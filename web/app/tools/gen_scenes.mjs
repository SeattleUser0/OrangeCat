// Orange Cat web app: web/app/lib/scenes.js from the scene bytes of Session C's engine pictures (tests/ui_scenes.h, branch ui-design,
// dumped by web/app/tools/scene_dump.c). The page draws them with lib/scene_svg.js, a port of tests/ui_scene.h's interpreter.
//   node web/app/tools/gen_scenes.mjs scenes.json COMMIT
// When tests/ui_scenes.h is on this branch (once ui-design is merged), tests/run_tests.sh can dump it and check this file with
// --check; until then the file records the commit of ui-design it came from.
// Revisions:
//   0.14.2: first version (Session D), from ui-design 776adb5 (UI_DESIGN.md 0.1).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "lib", "scenes.js");
export function scenesText(json, commit) {
  return "// SPDX-License-Identifier: GPL-3.0-only\n" +
    `// GENERATED by web/app/tools/gen_scenes.mjs from tests/ui_scenes.h (branch ui-design ${commit}: Session C's engine pictures). Do not edit.\n` +
    `export const SCENES_FROM = "ui-design ${commit}";\n` +
    "export const SCENES = " + JSON.stringify(json) + ";\n";
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const json = JSON.parse(readFileSync(process.argv[2], "utf8")), commit = process.argv[3] || "?";
  const t = scenesText(json, commit);
  if (process.argv.includes("--check")) { if (readFileSync(OUT, "utf8") !== t) { console.error("lib/scenes.js differs"); process.exit(1); } }
  else { writeFileSync(OUT, t); console.log("wrote " + OUT); }
}
