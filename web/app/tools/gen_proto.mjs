// Orange Cat web app: web/app/lib/editor_proto.js, made from the old editor's protocol section.
//
//   node web/app/tools/gen_proto.mjs           write web/app/lib/editor_proto.js
//   node web/app/tools/gen_proto.mjs --check   exit 1 when the file differs from what editor.html gives now
//
// The app speaks to the unit with the same code the old editor (web/editor.html) does: the text between its /*PROTO-BEGIN*/ and
// /*PROTO-END*/ markers (the framing, every request and reply, the Link, the library, the module and pack checks, the mock unit).
// That text is copied here unchanged and made a module that exports every top-level name. web/app/test/run.mjs runs --check, so a
// change to the editor's protocol code without regenerating this file fails the tests: the two pages cannot drift.
//
// Revisions:
//   0.14.2: first version (Session D).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = join(HERE, "..", "..");
const OUT = join(HERE, "..", "lib", "editor_proto.js");

export function makeProto(html = readFileSync(join(WEB, "editor.html"), "utf8")) {
  const a = html.indexOf("/*PROTO-BEGIN*/"), b = html.indexOf("/*PROTO-END*/");
  if (a < 0 || b < a) throw new Error("editor.html: no PROTO-BEGIN / PROTO-END markers");
  const body = html.slice(a, b + "/*PROTO-END*/".length);
  // every name declared at the top level of the section (a line that starts with the declaration)
  const names = new Set();
  for (const m of body.matchAll(/^(?:const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  return [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// GENERATED by web/app/tools/gen_proto.mjs from web/editor.html (the text between PROTO-BEGIN and PROTO-END), unchanged.",
    "// Do not edit: change web/editor.html and run `node web/app/tools/gen_proto.mjs`. web/app/test/run.mjs checks the two agree.",
    "// The editor's own copyright and license notices are those of web/editor.html (Kerem Kilic (Ellic Studio); portions Leo Kuroshita, Hügelton Instruments).",
    "/* eslint-disable */",
    body,
    "",
    `export { ${[...names].sort().join(", ")} };`,
    "",
  ].join("\n");
}

// The editor's English and Japanese texts (its `const TEXT = {...};`), for the messages the moved code raises (the keys of the module, pack and
// backup errors, the Engines table's states). Copied unchanged, as editor_text.js.
const OUT_TEXT = join(HERE, "..", "lib", "editor_text.js");
export function makeText(html = readFileSync(join(WEB, "editor.html"), "utf8")) {
  const a = html.indexOf("const TEXT = {");
  const b = html.indexOf("\n};", a);
  if (a < 0 || b < 0) throw new Error("editor.html: no const TEXT = { ... };");
  return [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// GENERATED by web/app/tools/gen_proto.mjs from web/editor.html (its TEXT table), unchanged. Do not edit.",
    html.slice(a, b + 3),
    "",
    "export { TEXT };",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = makeProto(), tt = makeText();
  if (process.argv.includes("--check")) {
    let now = "";
    try { now = readFileSync(OUT, "utf8"); } catch (_) { /* none yet */ }
    let nowT = "";
    try { nowT = readFileSync(OUT_TEXT, "utf8"); } catch (_) { /* none yet */ }
    if (now !== text || nowT !== tt) { console.error("web/app/lib/editor_proto.js or editor_text.js is not what web/editor.html gives: run node web/app/tools/gen_proto.mjs"); process.exit(1); }
    console.log("editor_proto.js and editor_text.js match editor.html");
  } else {
    writeFileSync(OUT, text);
    writeFileSync(OUT_TEXT, tt);
    console.log(`wrote ${OUT} and ${OUT_TEXT}`);
  }
}
