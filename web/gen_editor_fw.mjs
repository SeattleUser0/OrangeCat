// web-r3 round 3 (Session D), audit E3 / E10 / E11: the firmware's words for DUB TAPE's values, written into editor.html between
// /*FW-DUB-BEGIN*/ and /*FW-DUB-END*/ from web/app/lib/fw_tables.js (which tests/web_tables.c writes through param_format).
//   node web/gen_editor_fw.mjs          rewrite the block        node web/gen_editor_fw.mjs --check     fail when it is not what the tables say
import { readFileSync, writeFileSync } from "node:fs";
import { FW } from "./app/lib/fw_tables.js";

const file = new URL("editor.html", import.meta.url);
const cell = (title, label, sync) => { const p = FW.pages.find((x) => x.title === title); return (sync ? FW.cellsDubSync : FW.cells)[p.i].find((c) => c && c.label === label); };
const text = (c) => FW.classes[c.c].text;
const D = FW.dub;
const data = {
  mode: D.mode, tape: D.tape, mark: D.mark, driveN: D.driveN, wowN: D.wowN,
  sync: D.sync, ping: D.ping, drive: D.drive, wow: D.wow,
  syncText: text(cell("DUB SETUP", "SYNC")), pingText: text(cell("DUB SETUP", "PING")),
  driveText: text(cell("DUB 2", "DRIVE")), wowText: text(cell("DUB 2", "WOW")),
  tim: text(cell("DUB SETUP", "TIM L", false)), timSync: text(cell("DUB SETUP", "TIM L", true)),
  speed: text(cell("DUB 2", "SPEED")),
};
const block = `/*FW-DUB-BEGIN*/
/* GENERATED by web/gen_editor_fw.mjs from web/app/lib/fw_tables.js (tests/web_tables.c: the firmware's param_format and dub_fields.h). Do not edit. */
const DUBFW = ${JSON.stringify(data)};
/*FW-DUB-END*/`;
const html = readFileSync(file, "utf8");
const a = html.indexOf("/*FW-DUB-BEGIN*/"), b = html.indexOf("/*FW-DUB-END*/");
if (a < 0 || b < 0) { console.error("editor.html has no FW-DUB block"); process.exit(1); }
const out = html.slice(0, a) + block + html.slice(b + "/*FW-DUB-END*/".length);
if (process.argv.includes("--check")) {
  if (out !== html) { console.error("editor.html's DUB block is not what web/app/lib/fw_tables.js says: run node web/gen_editor_fw.mjs"); process.exit(1); }
  console.log("editor.html's DUB block == the firmware's tables"); process.exit(0);
}
writeFileSync(file, out);
console.log("editor.html: DUB block written");
